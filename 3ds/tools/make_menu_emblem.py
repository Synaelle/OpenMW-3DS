#!/usr/bin/env python3
"""Renders the start menu's top screen picture (M15): the moon-and-star emblem of the HOME Menu icon
(packaging/source/morrowind_emblem.png, supplied by the tester), scaled and blended over the menu's background
colour, into platform3ds/src/menuemblem.inc (committed; run again only when the emblem, its size or the background
colour changes):

    python tools/make_menu_emblem.py

The pixels are stored the way the top screen's framebuffer holds them (BGR8, rotated: column by column, each
column from the bottom of the screen to the top), so platform3ds/src/menuart.cpp copies whole columns.
"""

import os

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EMBLEM = os.path.join(ROOT, "packaging", "source", "morrowind_emblem.png")
OUT = os.path.join(ROOT, "platform3ds", "src", "menuemblem.inc")
SIZE = 176
BACKGROUND = (18, 14, 11)  # menuart::colour::background (platform3ds/include/platform3ds/menuart.hpp)


def main():
    emblem = Image.open(EMBLEM).convert("RGBA").resize((SIZE, SIZE), Image.LANCZOS)
    picture = Image.new("RGB", (SIZE, SIZE), BACKGROUND)
    picture.paste(emblem, (0, 0), emblem)
    px = picture.load()
    data = bytearray()
    for x in range(SIZE):
        for y in reversed(range(SIZE)):
            r, g, b = px[x, y]
            data += bytes((b, g, r))
    lines = [
        "// GENERATED by tools/make_menu_emblem.py from packaging/source/morrowind_emblem.png - edit the tool, not",
        "// this file. BGR8, column by column, each column bottom to top.",
        "",
        f"constexpr int kEmblemSize = {SIZE};",
        "constexpr uint8_t kEmblem[] = {",
    ]
    for i in range(0, len(data), 30):
        lines.append("    " + ", ".join(str(b) for b in data[i:i + 30]) + ",")
    lines.append("};")
    lines.append("")
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"{SIZE}x{SIZE}, {len(data)} bytes, wrote {OUT}")


if __name__ == "__main__":
    main()
