#!/usr/bin/env python3
"""Renders the start menu's font (M15): OpenMW's MysticCards (resources/vfs/fonts/MysticCards.ttf, SIL Open Font
License 1.1: free to embed with any software, its licence shipped alongside; a look-alike of Morrowind's own font,
none of the game's assets) at the menu's two sizes, printable ASCII, into platform3ds/src/menufont.inc (committed;
run again only to change the sizes or characters):

    python tools/make_menu_font.py

Each glyph: its 8-bit coverage (anti-aliased, FreeType's), its size, its offset from the pen (left, from the line's
top) and its advance. platform3ds/src/textfb.cpp blends the coverage over the bottom screen's RGB565 framebuffer.
"""

import os

import freetype

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TTF = os.path.join(ROOT, "..", "files", "data", "fonts", "MysticCards.ttf")
OUT = os.path.join(ROOT, "platform3ds", "src", "menufont.inc")
SIZES = {"Title": 23, "Text": 17, "Small": 13}  # pixels per em
CODES = range(32, 127)


def render(size):
    face = freetype.Face(TTF)
    face.set_pixel_sizes(0, size)
    ascent = face.size.ascender >> 6
    line_height = (face.size.ascender - face.size.descender) >> 6
    glyphs, data = [], bytearray()
    for code in CODES:
        face.load_char(chr(code), freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_NORMAL)
        g = face.glyph
        w, h = g.bitmap.width, g.bitmap.rows
        pitch = g.bitmap.pitch
        offset = len(data)
        for row in range(h):
            data += bytes(g.bitmap.buffer[row * pitch: row * pitch + w])
        glyphs.append((g.bitmap_left, ascent - g.bitmap_top, w, h, (g.advance.x + 32) >> 6, offset))
    return ascent, line_height, glyphs, data


def main():
    lines = [
        "// GENERATED by tools/make_menu_font.py from OpenMW's MysticCards.ttf (SIL Open Font License 1.1,",
        "// openmw/files/data/fonts/MysticCardsFontLicense.txt) - edit the tool, not this file.",
        "// Glyphs " + str(CODES.start) + "-" + str(CODES.stop - 1) + ": { left, top, width, height, advance, offset }.",
        "",
    ]
    for name, size in SIZES.items():
        ascent, line_height, glyphs, data = render(size)
        lines.append(f"constexpr int k{name}LineHeight = {line_height};")
        lines.append(f"constexpr MenuGlyph k{name}Glyphs[] = {{")
        for left, top, w, h, advance, offset in glyphs:
            lines.append(f"    {{ {left}, {top}, {w}, {h}, {advance}, {offset} }},")
        lines.append("};")
        lines.append(f"constexpr uint8_t k{name}Coverage[] = {{")
        for i in range(0, len(data), 24):
            lines.append("    " + ", ".join(str(b) for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append("")
        print(f"{name}: {size} px, line {line_height}, {len(data)} bytes of coverage")
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
