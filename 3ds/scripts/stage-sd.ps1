# Stages an SD-card layout for OpenMW 3DS (see components/files/threedspath.hpp):
#   <SdRoot>/openmw/openmw.cfg, defaults.bin, resources/   (from the OpenMW build)
#   <SdRoot>/openmw/config/openmw.cfg   data path, content, encoding, fallbacks from Morrowind.ini
#   <SdRoot>/openmw/config/settings.cfg 3DS settings (packaging/settings-3ds.cfg)
#   <SdRoot>/openmw/{cache,saves,data}  pre-created (directory creation costs ~1.5 s on real SD)
#   <SdRoot>/openmw/data                -> -DataMode junction: a junction to the Morrowind "Data Files"
#                                          (emulator only; Morrowind data is never copied or modified)
#
#   scripts\stage-sd.ps1                                   # Azahar's virtual SD, data junction
#   scripts\stage-sd.ps1 -SdRoot out\sdcard -DataMode none # hardware package (data added separately)
param(
    [string]$SdRoot = (Join-Path $env:APPDATA 'Azahar\sdmc'),
    [ValidateSet('junction', 'none')][string]$DataMode = 'junction',
    [string]$MorrowindDir = 'D:\SteamLibrary\steamapps\common\Morrowind',
    [string[]]$Content = @('Morrowind.esm'),
    [string]$Args = ''
)
$ErrorActionPreference = 'Stop'
$RepoRoot = Split-Path -Parent $PSScriptRoot
$Build = Join-Path $RepoRoot 'build\openmw'
$Dst = Join-Path $SdRoot 'openmw'
$DataFiles = Join-Path $MorrowindDir 'Data Files'

foreach ($d in 'config', 'cache', 'saves', 'screenshots') { New-Item -ItemType Directory -Force (Join-Path $Dst $d) | Out-Null }

# Local (engine) files from the build.
Copy-Item (Join-Path $Build 'openmw.cfg') $Dst -Force
Copy-Item (Join-Path $Build 'defaults.bin') $Dst -Force
$res = Join-Path $Dst 'resources'
if (Test-Path $res) { Remove-Item -Recurse -Force $res }
Copy-Item -Recurse (Join-Path $Build 'resources') $res

# User openmw.cfg: what the PC launcher/wizard would write.
$cfg = New-Object System.Collections.Generic.List[string]
$cfg.Add('# OpenMW 3DS user configuration (generated by scripts/stage-sd.ps1)')
$cfg.Add('data="/openmw/data"') # POSIX-absolute on the SD card (see threedspath.cpp)
foreach ($c in $Content) { $cfg.Add("content=$c") }
foreach ($bsa in 'Morrowind.bsa') { $cfg.Add("fallback-archive=$bsa") }
$cfg.Add('encoding=win1252')
$ini = Join-Path $MorrowindDir 'Morrowind.ini'
if (Test-Path $ini) {
    $fallbacks = & python (Join-Path $RepoRoot 'tools\mwini_fallbacks.py') $ini
    if ($LASTEXITCODE -ne 0) { throw 'fallback import failed' }
    $cfg.AddRange([string[]]$fallbacks)
} else {
    Write-Warning "no Morrowind.ini at ${ini}: fallback values missing"
}
[IO.File]::WriteAllLines((Join-Path $Dst 'config\openmw.cfg'), $cfg)
Copy-Item (Join-Path $RepoRoot 'packaging\settings-3ds.cfg') (Join-Path $Dst 'config\settings.cfg') -Force

$argsFile = Join-Path $Dst 'args.txt'
if ($Args) { Set-Content $argsFile (($Args -split ' ') -join "`n") } elseif (Test-Path $argsFile) { Remove-Item $argsFile }

# Game data.
$data = Join-Path $Dst 'data'
if ($DataMode -eq 'junction') {
    if (-not (Test-Path (Join-Path $DataFiles 'Morrowind.esm'))) { throw "Morrowind.esm not found in $DataFiles" }
    $item = Get-Item $data -ErrorAction SilentlyContinue
    if ($item -and -not ($item.Attributes -band [IO.FileAttributes]::ReparsePoint)) { throw "$data exists and is not a junction; refusing to touch it" }
    if (-not $item) { New-Item -ItemType Junction -Path $data -Target $DataFiles | Out-Null }
} else {
    New-Item -ItemType Directory -Force $data | Out-Null
}

Write-Host "Staged $Dst (data: $DataMode)"
Get-ChildItem $Dst | Select-Object Name, @{ n = 'Type'; e = { if ($_.PSIsContainer) { 'dir' } else { "$([math]::Round($_.Length/1KB)) KB" } } } | Format-Table -AutoSize
