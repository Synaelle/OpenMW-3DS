# Stages an SD-card layout for OpenMW 3DS (see components/files/threedspath.hpp). The folder is the build's
# (CMakeLists.txt OPENMW3DS_SD_DIR): openmw-test for test builds, which also read the player's install (openmw) as
# their first data folder, read only, so a hardware test needs neither the game's files nor the sounds and textures
# again; openmw for a release build (-SdDir openmw). Below, "openmw" stands for either.
#   <SdRoot>/openmw/openmw.cfg, defaults.bin, resources/   (from the OpenMW build)
#   <SdRoot>/openmw/config/openmw.cfg   data path, content, encoding, fallbacks from Morrowind.ini
#   <SdRoot>/openmw/config/settings.cfg 3DS settings (packaging/settings-3ds.cfg)
#   <SdRoot>/openmw/{cache,saves,data,logs,screenshots}  pre-created (directory creation costs ~1.5 s on real SD)
#   <SdRoot>/openmw/data                what the console's data folder holds: the content files, Morrowind.bsa and
#                                          sound3ds.bsa (Sound and Music packed by tools\pack_sound_bsa.py, once).
#                                          -DataMode junction (emulator): a junction to out\emu-data, which holds
#                                          copies of the content files and Morrowind.bsa (read from the Morrowind
#                                          data, which is never modified) and sound3ds.bsa. -DataMode none (hardware
#                                          package): only sound3ds.bsa. The tester adds their own files.
#   <SdRoot>/openmw/cooked/textures.o3tp   textures converted for the 3DS GPU (out\cooked, cooked on
#                                          first use by tools\cook_textures.py, a junction in the emulator)
#
#   scripts\stage-sd.ps1                                   # Azahar's virtual SD, data junction
#   scripts\stage-sd.ps1 -SdRoot out\sdcard -DataMode none # hardware package (the player's install has the data)
param(
    [string]$SdRoot = (Join-Path $env:APPDATA 'Azahar\sdmc'),
    [ValidateSet('junction', 'none')][string]$DataMode = 'junction',
    [string]$MorrowindDir = 'D:\SteamLibrary\steamapps\common\Morrowind',
    [string[]]$Content = @('Morrowind.esm'),
    [string]$Args = '',
    [string]$SdDir = 'openmw-test'
)
$ErrorActionPreference = 'Stop'
$RepoRoot = Split-Path -Parent $PSScriptRoot
$Build = Join-Path $RepoRoot 'build\openmw'
$Dst = Join-Path $SdRoot $SdDir
$DataFiles = Join-Path $MorrowindDir 'Data Files'

foreach ($d in 'config', 'cache', 'saves', 'screenshots', 'logs') { New-Item -ItemType Directory -Force (Join-Path $Dst $d) | Out-Null }

# Local (engine) files from the build.
Copy-Item (Join-Path $Build 'openmw.cfg') $Dst -Force
Copy-Item (Join-Path $Build 'defaults.bin') $Dst -Force
$res = Join-Path $Dst 'resources'
if (Test-Path $res) { Remove-Item -Recurse -Force $res }
Copy-Item -Recurse (Join-Path $Build 'resources') $res

# User openmw.cfg: what the PC launcher/wizard would write.
$cfg = New-Object System.Collections.Generic.List[string]
$cfg.Add('# OpenMW 3DS user configuration (generated by scripts/stage-sd.ps1)')
if ($SdDir -ne 'openmw') {
    # A test install: the player's game files first (read only, never written), then its own data folder, whose
    # files win when a test brings different ones (another edition, a newer sound archive).
    $cfg.Add('data="/openmw/data"')
}
$cfg.Add("data=""/$SdDir/data""") # POSIX-absolute on the SD card (see threedspath.cpp)
# M8: the 3DS UI's layouts (packaging/ui3ds), after the game's data so they replace OpenMW's own.
$cfg.Add("data=""/$SdDir/ui3ds""")
foreach ($c in $Content) { $cfg.Add("content=$c") }
foreach ($bsa in 'Morrowind.bsa', 'sound3ds.bsa') { $cfg.Add("fallback-archive=$bsa") }
$cfg.Add('encoding=win1252')
$ini = Join-Path $MorrowindDir 'Morrowind.ini'
if (Test-Path $ini) {
    $fallbacks = & python (Join-Path $RepoRoot 'tools\mwini_fallbacks.py') $ini
    if ($LASTEXITCODE -ne 0) { throw 'fallback import failed' }
    $cfg.AddRange([string[]]$fallbacks)
} else {
    Write-Warning "no Morrowind.ini at ${ini}: fallback values missing"
}
[IO.File]::WriteAllLines((Join-Path $Dst 'config\openmw.cfg'), $cfg)
Copy-Item (Join-Path $RepoRoot 'packaging\settings-3ds.cfg') (Join-Path $Dst 'config\settings.cfg') -Force

$argsFile = Join-Path $Dst 'args.txt'
if ($Args) { Set-Content $argsFile (($Args -split ' ') -join "`n") } elseif (Test-Path $argsFile) { Remove-Item $argsFile }

# Sounds and music packed into one archive (tools/pack_sound_bsa.py), packed once from the Morrowind data (read
# only): indexing the ~7,200 loose files took 12.8 s at startup and 3.3 MB of heap.
$cookedSrc = Join-Path $RepoRoot 'out\cooked'
$soundBsa = Join-Path $cookedSrc 'sound3ds.bsa'
# A test hardware package brings neither sounds nor textures (the player's install has them): nothing to pack.
$needsGameAssets = $DataMode -eq 'junction' -or $SdDir -eq 'openmw'
if ($needsGameAssets -and -not (Test-Path $soundBsa)) {
    & python -I (Join-Path $RepoRoot 'tools\pack_sound_bsa.py') $DataFiles $soundBsa
    if ($LASTEXITCODE -ne 0) { throw 'sound packing failed' }
}

# Game data.
$data = Join-Path $Dst 'data'
if ($DataMode -eq 'junction') {
    if (-not (Test-Path (Join-Path $DataFiles 'Morrowind.esm'))) { throw "Morrowind.esm not found in $DataFiles" }
    # The emulator sees what the console sees: not the loose Sound and Music folders, which would override
    # sound3ds.bsa (loose files win) and take seconds to index.
    $emuData = Join-Path $RepoRoot 'out\emu-data'
    New-Item -ItemType Directory -Force $emuData | Out-Null
    foreach ($f in @($Content) + @('Morrowind.bsa')) {
        $copy = Join-Path $emuData $f
        if (-not (Test-Path $copy)) { Copy-Item (Join-Path $DataFiles $f) $copy }
    }
    $link = Join-Path $emuData 'sound3ds.bsa'
    if (Test-Path $link) { Remove-Item $link -Force }
    New-Item -ItemType HardLink -Path $link -Target $soundBsa | Out-Null
    $item = Get-Item $data -ErrorAction SilentlyContinue
    if ($item -and -not ($item.Attributes -band [IO.FileAttributes]::ReparsePoint)) { throw "$data exists and is not a junction; refusing to touch it" }
    if ($item -and $item.Target -ne $emuData) {
        # Non-recursive: removes the junction itself, never what it points to.
        [IO.Directory]::Delete($data, $false)
        $item = $null
    }
    if (-not $item) { New-Item -ItemType Junction -Path $data -Target $emuData | Out-Null }
} else {
    New-Item -ItemType Directory -Force $data | Out-Null
    # A release-like install brings its sounds, a test one reads the player's (openmw/data).
    if ($SdDir -eq 'openmw') { Copy-Item $soundBsa $data -Force }
}

# The 3DS UI's MyGUI files (M8): a junction to the repository's in the emulator (edits apply at the next run), a copy
# in the hardware package.
$ui3ds = Join-Path $Dst 'ui3ds'
$ui3dsSrc = Join-Path $RepoRoot 'packaging\ui3ds'
if ($DataMode -eq 'junction') {
    $item = Get-Item $ui3ds -ErrorAction SilentlyContinue
    if ($item -and -not ($item.Attributes -band [IO.FileAttributes]::ReparsePoint)) { Remove-Item -Recurse -Force $ui3ds; $item = $null }
    if (-not $item) { New-Item -ItemType Junction -Path $ui3ds -Target $ui3dsSrc | Out-Null }
} else {
    if (Test-Path $ui3ds) { Remove-Item -Recurse -Force $ui3ds }
    Copy-Item -Recurse $ui3dsSrc $ui3ds
}

# Textures cooked for the PICA (tools/cook_textures.py), cooked once from the Morrowind data (read only).
$pack = Join-Path $cookedSrc 'textures.o3tp'
if ($needsGameAssets -and -not (Test-Path $pack)) {
    & python (Join-Path $RepoRoot 'tools\cook_textures.py') --data $DataFiles --resources (Join-Path $Build 'resources\vfs') --out $pack
    if ($LASTEXITCODE -ne 0) { throw 'texture cooking failed' }
}
$cooked = Join-Path $Dst 'cooked'
if ($DataMode -eq 'junction') {
    $item = Get-Item $cooked -ErrorAction SilentlyContinue
    if ($item -and -not ($item.Attributes -band [IO.FileAttributes]::ReparsePoint)) { Remove-Item -Recurse -Force $cooked; $item = $null }
    if (-not $item) { New-Item -ItemType Junction -Path $cooked -Target $cookedSrc | Out-Null }
} elseif ($SdDir -eq 'openmw') {
    New-Item -ItemType Directory -Force $cooked | Out-Null
    Copy-Item $pack $cooked -Force
}
# (A test install without its own pack reads the player's, openmw/cooked: n3ds/main3ds.cpp.)

Write-Host "Staged $Dst (data: $DataMode)"
Get-ChildItem $Dst | Select-Object Name, @{ n = 'Type'; e = { if ($_.PSIsContainer) { 'dir' } else { "$([math]::Round($_.Length/1KB)) KB" } } } | Format-Table -AutoSize
