#!/usr/bin/env python3
"""Generates scene.v.pica (committed): the scene vertex shader with its point lights unrolled.

    python openmw/components/render3ds/gen_scene_shader.py

No flow control on purpose. Hardware test #12 hung the GPU at the first draw using the previous version, whose
light loop (LOOP with aL-relative uniform access) ran fine in every emulator, while the M0 test app's shader
(straight-line code) runs on hardware. Unused lights are uploaded far away with a zero radius, so they cost
instructions but contribute nothing.
"""

import os

LIGHTS = 8

HEADER = """; OpenMW 3DS port: scene vertex shader (citro3d backend, components/render3ds/backend.cpp).
; GENERATED by gen_scene_shader.py - edit the generator, not this file.
;
; OpenMW's object lighting (files/shaders/lib/light/util.glsl, compatibility/objects.frag) evaluated per
; vertex instead of per pixel:
;   lighting = D * (sun.diffuse * lambert + sum(light.diffuse * lambert * att))
;            + A * (sun.ambient + sum(light.ambient * att)) + E
;   color.rgb = clamp(lighting, 0, 1), color.a = D.a * alpha
; With lighting.x = 0 the light terms drop out and color.rgb = E: unlit draws (the sky passes).
; D, A, E are the material diffuse/ambient/emission colors, or the vertex color when the material's
; vertex color mode says so (colorSel). The TEV stage then multiplies by the diffuse texture.
;
; Inputs: v0 position, v1 normal, v2 color (unsigned bytes, 0..255), v3 texcoord0.
; Outputs texcoord0 through texMat (the diffuse map's UV animation / terrain layer tiling) and texcoord1 through
; texMat1 (the terrain blend map, texture unit 1), both from the one texcoord input.
;
; Straight-line code only: the point lights are unrolled ({lights} of them), no LOOP/IF (a LOOP version hung
; real hardware, test #12). Every output component is written exactly once; attenuation is capped so no
; inf/NaN reaches the color.

.fvec projection[4]
.fvec modelView[4]
.fvec texMat[2]
.fvec texMat1[2]
.fvec sunDir, sunDiffuse, sunAmbient
.fvec matDiffuse, matAmbient, matEmission
.fvec colorSel      ; x/y/z: diffuse/ambient/emission come from the vertex color (0 or 1); w: alpha multiplier
.fvec lighting      ; x: 1 = lit, 0 = unlit (only E); y: 1 = E fades to matAmbient as the vertex alpha drops (clouds)
.fvec lights[{uniforms}]    ; {lights} point lights x 4: (view position, 4/radius), diffuse, ambient, (constant, linear, quadratic, 0)

.constf consts(0.0, 1.0, 0.00392156863, 3.0)
.constf limits(1000000.0, 0.0, 0.0, 0.0)

.out outpos position
.out outclr color
.out outtc0 texcoord0
.out outtc1 texcoord1

.alias inpos v0
.alias innrm v1
.alias inclr v2
.alias intex v3

.alias zeros consts.xxxx
.alias ones  consts.yyyy

.proc main
	; r0 = view-space position
	mov r1.xyz, inpos
	mov r1.w, ones
	dp4 r0.x, modelView[0], r1
	dp4 r0.y, modelView[1], r1
	dp4 r0.z, modelView[2], r1
	mov r0.w, ones

	dp4 outpos.x, projection[0], r0
	dp4 outpos.y, projection[1], r0
	dp4 outpos.z, projection[2], r0
	dp4 outpos.w, projection[3], r0

	; texture coordinates through the texture matrix (UV animation), written in one go
	mov r1.xy, intex
	mov r1.z, zeros
	mov r1.w, ones
	dp4 r14.x, texMat[0], r1
	dp4 r14.y, texMat[1], r1
	mov r14.z, zeros
	mov r14.w, ones
	mov outtc0, r14
	dp4 r13.x, texMat1[0], r1
	dp4 r13.y, texMat1[1], r1
	mov r13.z, zeros
	mov r13.w, ones
	mov outtc1, r13

	; r2 = normalized view-space normal
	dp3 r2.x, modelView[0], innrm
	dp3 r2.y, modelView[1], innrm
	dp3 r2.z, modelView[2], innrm
	dp3 r3.x, r2, r2
	rsq r3.x, r3.x
	mul r2.xyz, r2, r3.xxxx

	; r5 = vertex color 0..1
	mul r5, consts.zzzz, inclr

	; r3 = D, r4 = A (material color, or the vertex color)
	add r8, -matDiffuse, r5
	mov r9, matDiffuse
	mad r3, r8, colorSel.xxxx, r9
	add r8, -matAmbient, r5
	mov r9, matAmbient
	mad r4, r8, colorSel.yyyy, r9

	; r6 = diffuse light, r7 = ambient light: sun first
	dp3 r8.x, sunDir, r2
	max r8.x, zeros, r8.x
	mul r6.xyz, sunDiffuse, r8.xxxx
	mov r7.xyz, sunAmbient
"""

LIGHT = """
	; point light {index}: r8 = direction, r9 = (d^2, 1/d, d), r10.x = lambert, r11.x = attenuation
	add r8.xyz, lights[{p}], -r0
	dp3 r9.x, r8, r8
	rsq r9.y, r9.x
	mul r8.xyz, r8, r9.yyyy
	mul r9.z, r9.x, r9.y
	dp3 r10.x, r8, r2
	max r10.x, zeros, r10.x
	mov r11.x, ones
	mov r11.y, r9.z
	mov r11.z, r9.x
	dp3 r11.x, lights[{a}], r11
	rcp r11.x, r11.x
	min r11.x, limits.xxxx, r11.x
	; radius fade: x = clamp(4 * d / radius - 3, 0, 1); att *= (1 - x^2)^2
	mul r12.x, lights[{p}].wwww, r9.z
	add r12.x, -consts.wwww, r12.x
	max r12.x, zeros, r12.x
	min r12.x, ones, r12.x
	mul r12.x, r12.x, r12.x
	add r12.x, ones, -r12.x
	mul r12.x, r12.x, r12.x
	mul r11.x, r11.x, r12.x
	mul r10.x, r10.x, r11.x
	mad r6.xyz, r10.xxxx, lights[{d}], r6
	mad r7.xyz, r11.xxxx, lights[{m}], r7
"""

FOOTER = """
	; E: material emission, or the vertex color
	add r8, -matEmission, r5
	mov r9, matEmission
	mad r9, r8, colorSel.zzzz, r9

	; sky clouds (lighting.y = 1): E = mix(matAmbient, E, vertex alpha), sky.frag's fade to the fog color at the
	; horizon (matAmbient holds the fog color then). t = 1 + (alpha - 1) * lighting.y
	add r11.x, -ones, r5.w
	mul r11.x, lighting.yyyy, r11.x
	add r11.x, ones, r11.x
	add r8, -matAmbient, r9
	mul r8, r8, r11.xxxx
	add r9, matAmbient, r8

	; lighting = D * diffuseLight + A * ambientLight + E, clamped
	mul r10.xyz, r3, r6
	mad r10.xyz, r4, r7, r10
	mul r10.xyz, lighting.xxxx, r10
	add r10.xyz, r9, r10
	max r10.xyz, zeros, r10
	min r10.xyz, ones, r10
	mul r10.w, colorSel.wwww, r3.w
	mov outclr, r10
	end
.end
"""


def main():
    text = HEADER.format(lights=LIGHTS, uniforms=LIGHTS * 4)
    for i in range(LIGHTS):
        base = i * 4
        text += LIGHT.format(index=i, p=base, d=base + 1, m=base + 2, a=base + 3)
    text += FOOTER
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "scene.v.pica")
    with open(out, "w", newline="\n") as f:
        f.write(text)
    print("wrote", out)


if __name__ == "__main__":
    main()
